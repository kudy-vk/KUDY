//   node docs/design/brand/outputs/ADS-01/build-specimen.mjs
// The board is a proposal, not production UI; test/ads-01-layout.test.mjs
// re-computes every number and fails when the committed specimen drifts.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  CANVAS_W,
  DEVICES,
  bannerEnvelope,
  layout,
  pieceRects,
} from './layout-math.mjs';
import { nativeLayout } from '../menu-map-city-only/native-layout.ts';

const here = dirname(fileURLToPath(import.meta.url));
const round = (n) => Math.round(n * 100) / 100;
const variantA = { variant: 'packed', family: 'anchored', bannerHeight: 50, footerHeight: 96 };
const variantB = { variant: 'bottom-anchored', family: 'anchoredLarge', bannerHeight: 90, footerHeight: 96 };
const variants = [
  { key: 'A', title: 'A — ад верху (для параўнання, не выбрана): карта → банэр → футэр', cfg: variantA },
  { key: 'B', title: 'B — ад ніза экрана (рашэнне ўладара 02.11.2026)', cfg: variantB },
];
const pieces = pieceRects(nativeLayout);
const worst = DEVICES.map((d) => {
  const cap = bannerEnvelope('anchoredLarge', d).cap;
  const r = layout(d, { variant: 'bottom-anchored', family: 'anchoredLarge', bannerHeight: cap, footerHeight: 128 });
  return { device: d, cap, gap: round(r.mapBannerGap), overlap: r.overlapsMap };
});

function frame(device, v, theme) {
  const r = layout(device, v.cfg);
  const scale = device.width / CANVAS_W;
  const pieceDivs = pieces
    .map(
      (p) =>
        `<div class="piece" style="left:${(p.x * scale).toFixed(1)}px;top:${(p.y * scale).toFixed(1)}px;width:${(p.w * scale).toFixed(1)}px;height:${(p.h * scale).toFixed(1)}px">${p.id}</div>`,
    )
    .join('');
  const banner = `<div class="banner" style="top:${r.bannerRect.top}px;height:${v.cfg.bannerHeight}px">банэр · ${v.cfg.family} · ${v.cfg.bannerHeight}dp</div>`;
  const footer = `<div class="footer" style="top:${r.footerRect.top}px;height:${r.footerRect.height}px">выява футэра (#990) · ${r.footerRect.height}dp · не зацверджана</div>`;
  return `<div class="frame-wrap">
  <div class="frame-title">${device.id} · ${v.key}</div>
  <div class="frame ${theme}" style="width:${device.width}px;height:${device.height}px">
    <div class="inset top" style="height:${device.top}px">status ${device.top}</div>
    <div class="map" style="top:${device.top}px;height:${r.mapH}px">${pieceDivs}</div>
    ${banner}
    ${footer}
    <div class="inset bottom" style="height:${device.bottom}px">nav ${device.bottom}</div>
    ${r.overflow ? '<div class="overflow-flag">патрэбны скрол</div>' : ''}
  </div>
</div>`;
}

function rows(theme) {
  return DEVICES.map((d) =>
    variants
      .map((v) => {
        const r = layout(d, v.cfg);
        return `<tr data-device="${d.id}" data-variant="${v.key}" data-family="${v.cfg.family}" data-banner="${v.cfg.bannerHeight}" data-footer="${v.cfg.footerHeight}" data-map-h="${round(r.mapH)}" data-banner-top="${round(r.bannerRect.top)}" data-free="${round(r.freeSpace)}"><td>${theme === 'light' ? d.id : d.id + ' (dark)'}</td><td>${v.key}</td><td>${round(r.mapH)}</td><td>${round(r.bannerRect.top)}</td><td>${round(r.freeSpace)}</td><td>${r.overlapsMap ? 'ДА' : 'не'}</td><td>${r.overflow ? 'скрол' : 'змяшчаецца'}</td></tr>`;
      })
      .join(''),
  ).join('');
}

function section(theme) {
  return `<section class="board ${theme}">
<h2>${theme === 'light' ? 'Светлая тэма' : 'Цёмная тэма (нейтральныя колеры-заглушкі)'}</h2>
<div class="frames">${DEVICES.map((d) => variants.map((v) => frame(d, v, theme)).join('')).join('')}</div>
<table class="data">
<thead><tr><th>прылада</th><th>варыянт</th><th>карта dp</th><th>банэр top dp</th><th>вольна dp</th><th>перакрыцце</th><th>скрол</th></tr></thead>
<tbody>${rows(theme)}</tbody>
</table>
</section>`;
}

