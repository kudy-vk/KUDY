// Regenerates ../kit-icons.mjs from the Lucide package the app already ships
// (lucide-react-native), so mockups draw exactly the app's icon shapes.
// Run from the repository root: node docs/design/production/tools/gen-icons.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../../../..');
const pkgDir = path.join(root, 'node_modules/lucide-react-native');
const { version, license } = JSON.parse(fs.readFileSync(path.join(pkgDir, 'package.json'), 'utf8'));

const NAMES = [
  'arrow-left', 'bookmark', 'book-open', 'check', 'chevron-down', 'chevron-right', 'chevron-up', 'circle-alert',
  'clock', 'download', 'ellipsis-vertical', 'external-link', 'file-text', 'footprints', 'headphones',
  'hourglass', 'image', 'info', 'languages', 'layers', 'lightbulb', 'list', 'locate-fixed', 'lock', 'map', 'map-pin',
  'maximize-2', 'moon', 'navigation', 'pause', 'play', 'refresh-cw', 'rotate-ccw', 'route', 'search', 'settings',
  'skip-back', 'skip-forward', 'sliders-horizontal', 'square', 'star', 'sun', 'trash', 'type', 'user-round',
  'volume-2', 'wifi-off', 'x',
];

const icons = {};
for (const name of NAMES) {
  const source = fs.readFileSync(path.join(pkgDir, 'dist/esm/icons', `${name}.mjs`), 'utf8');
  const start = source.indexOf('[', source.indexOf('node:'));
  if (start < 0) throw new Error(`${name}: icon node not found`);
  let depth = 0, end = start;
  for (; end < source.length; end += 1) {
    if (source[end] === '[') depth += 1;
    if (source[end] === ']' && (depth -= 1) === 0) break;
  }
  // The literal is plain data (tag + attribute objects) from the installed package.
  const node = Function(`"use strict"; return (${source.slice(start, end + 1)});`)();
  icons[name] = node.map(([tag, attrs]) => {
    const { key, ...rest } = attrs;
    return [tag, rest];
  });
}

const lines = Object.entries(icons).map(([name, node]) => `  '${name}': ${JSON.stringify(node)},`);
const out = `// GENERATED by tools/gen-icons.mjs from lucide-react-native ${version} (${license}). Do not edit by hand.
export const ICONS = {
${lines.join('\n')}
};
`;
fs.writeFileSync(path.join(here, '../kit-icons.mjs'), out);
console.log(`kit-icons.mjs: ${Object.keys(icons).length} icons from lucide-react-native ${version}`);
